async fn seed_backup_passkey(
    args: &StorageArgs,
    passkeys: Arc<dyn storage::PasskeyStorage>,
    write_scope: storage::WriteScope,
    author: UserId,
) -> BackupPasskeyFixture {
    let credential = backup_passkey_credential();
    let credential_id = PasskeyCredentialId::from_credential(&credential);
    let label: PasskeyLabel = "Backup corpus Passkey"
        .parse()
        .expect("valid passkey fixture label");
    let passkeys_for_insert = Arc::clone(&passkeys);
    let credential_for_insert = credential.clone();
    let label_for_insert = label.clone();
    confirmed_for(
        write_scope
            .run(move |transaction| {
                Box::pin(async move {
                    passkeys_for_insert
                        .insert_credential(
                            transaction,
                            author,
                            &label_for_insert,
                            &credential_for_insert,
                        )
                        .await
                })
            })
            .await
            .expect("insert backup fixture passkey"),
        "insert backup fixture passkey",
    );
    set_backup_passkey_timestamps(args, &credential_id).await;
    let passkey = passkeys
        .credential(&credential_id)
        .await
        .expect("read backup fixture passkey")
        .expect("inserted backup fixture passkey");
    let user_handle = passkeys
        .user_handle(author)
        .await
        .expect("read backup fixture Passkey handle")
        .expect("backup fixture user has a Passkey handle");
    BackupPasskeyFixture {
        user_handle,
        credential_id,
        label,
        serialization: serde_json::to_value(&passkey.credential)
            .expect("serialize backup fixture passkey"),
        created_at: passkey.created_at,
        last_used_at: passkey
            .last_used_at
            .expect("used backup fixture passkey has last-used time"),
    }
}

/// Seeds a non-author subscriber and a `Named`-audience post they belong to,
/// returning `(viewer_id, audience_id, subscription_id, named_post_id)`. These visibility rows
/// (`subscriptions`, `audiences`, `audience_members`, `post_audiences`) must
/// survive restore so the subscriber still resolves the private post (issue #4).
async fn seed_named_audience_post(
    users: Arc<dyn storage::UserStorage>,
    subscriptions: Arc<dyn storage::SubscriptionStorage>,
    audiences: Arc<dyn storage::AudienceStorage>,
    posts: Arc<dyn storage::PostStorage>,
    write_scope: storage::WriteScope,
    author: UserId,
    password: &Password,
) -> (UserId, AudienceId, SubscriptionId, PostId) {
    let viewer_name: Username = "viewer".parse().expect("valid username");
    let display_name = parse_display_name("Viewer");
    let password = storage::prepare_password(password.clone())
        .await
        .expect("prepare viewer password");
    let outcome = write_scope
        .run(move |transaction| {
            Box::pin(async move {
                users
                    .create_user(
                        transaction,
                        &viewer_name,
                        &password,
                        Some(&display_name),
                        OperatorStatus::STANDARD,
                    )
                    .await
            })
        })
        .await
        .expect("create viewer");
    let viewer = confirmed_for(outcome, "backup fixture viewer");
    let subscription =
        seed_local_subscription(subscriptions, write_scope.clone(), author, viewer).await;
    let audience_name = parse_audience_name("friends");
    let audience_storage = Arc::clone(&audiences);
    let audience = confirmed_for(
        write_scope
            .run(move |transaction| {
                Box::pin(async move {
                    audience_storage
                        .create_audience(transaction, author, &audience_name)
                        .await
                })
            })
            .await
            .expect("create audience"),
        "backup fixture audience",
    );
    let audiences = Arc::clone(&audiences);
    confirmed_for(
        write_scope
            .run(move |transaction| {
                Box::pin(async move {
                    audiences
                        .add_member(transaction, author, audience, subscription)
                        .await
                })
            })
            .await
            .expect("add audience member"),
        "backup fixture audience membership",
    );
    let named_post = SeedRawPost::new(author)
        .published_at(fixture_published_at())
        .audiences(vec![AudienceTarget::Named(audience)])
        .seed(posts, write_scope)
        .await
        .post_id;
    (viewer, audience, subscription, named_post)
}

/// Seeds the side tables: a `user_config` row, a media-table row, and a
/// `feed_events` row.
async fn seed_side_tables(
    user_config: Arc<dyn storage::UserConfigStorage>,
    media: Arc<dyn storage::MediaStorage>,
    feed_events: Arc<dyn storage::FeedEventStorage>,
    write_scope: storage::WriteScope,
    author: UserId,
) {
    let key = UserConfigKey::DefaultPostFormat;
    let value = String::from("org");
    let content_license = ContentLicense::CcBySa4_0;
    confirmed_for(
        write_scope
            .run(move |transaction| {
                Box::pin(async move {
                    user_config.set(transaction, author, key, &value).await?;
                    user_config
                        .set(
                            transaction,
                            author,
                            UserConfigKey::ContentLicense,
                            content_license.as_ref(),
                        )
                        .await
                })
            })
            .await
            .expect("set user config"),
        "backup fixture user config",
    );
    let record = MediaRecord {
        user_id: author,
        sha256: parse_content_hash(FIXTURE_MEDIA_SHA256),
        filename: parse_filename("my%20photo.jpg"),
        source: MediaSource::Upload,
        content_type: parse_content_type("image/jpeg"),
        size_bytes: parse_byte_size("4"),
        source_url: None,
        created_at: fixture_published_at(),
    };
    confirmed_for(
        write_scope
            .run(move |transaction| {
                Box::pin(async move { media.create_media(transaction, &record).await })
            })
            .await
            .expect("create media row"),
        "backup fixture media",
    );
    let feed_path = fp("/feed.rss");
    confirmed_for(
        write_scope
            .run(move |transaction| {
                Box::pin(async move { feed_events.enqueue(transaction, &feed_path).await })
            })
            .await
            .expect("enqueue feed event"),
        "backup fixture feed event",
    );
}

