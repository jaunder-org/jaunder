/// Identifiers returned by [`populate_backup_fixture`] so
/// [`assert_backup_fixture_restored`] can check non-author visibility fidelity
/// (a `Named`-audience post must survive restore visible to its subscriber, not
/// silently Private — the bug in issue #4).
pub struct BackupFixtureIds {
    /// The operator who authors the fixture posts and owns the audience.
    pub author: UserId,
    /// A second, non-operator account subscribed to the author and a member of
    /// the `Named` audience — the viewer who must still see the private post.
    pub viewer: UserId,
    /// A `Public` post (visible to everyone, including anonymous).
    pub public_post: PostId,
    /// The public post's autogenerated slug and title, read back by
    /// [`assert_backup_fixture_restored`] instead of a hardcoded literal (both now
    /// autogenerate; only `published_at` stays a fixed contract).
    pub public_post_slug: Slug,
    pub public_post_title: PostTitle,
    /// A post targeted at a `Named` audience the viewer belongs to.
    pub named_post: PostId,
    /// The named audience assigned to `named_post` and containing `viewer`.
    pub audience: AudienceId,
    /// The subscription linking `viewer` to `author`, used by the audience member.
    pub subscription: SubscriptionId,
    /// The publisher generation, advanced from its migration-seeded value to prove
    /// backup and restore replace the target singleton row.
    pub publisher_generation: PublisherGeneration,
    pub passkey_user_handle: PasskeyUserHandle,
    /// The durable Passkey created for the author and verified after restore.
    pub passkey_credential_id: PasskeyCredentialId,
    pub passkey_label: PasskeyLabel,
    pub passkey_serialization: Value,
    pub passkey_created_at: UtcInstant,
    pub passkey_last_used_at: UtcInstant,
}

/// Fixed microsecond-precision publish time: deterministic and safe from
/// Postgres's µs quantization, so a restored value can be asserted exactly (DEC-D).
pub fn fixture_published_at() -> UtcInstant {
    "2026-04-29T12:34:56.789012Z"
        .parse()
        .expect("valid fixture timestamp")
}

/// A credential whose serialized counter and backup-state values are both
/// non-default, so a backup cannot silently omit either value.
fn backup_passkey_credential() -> Credential {
    let mut serialized =
        serde_json::to_value(passkey_credential_fixture()).expect("serialize passkey fixture");
    let credential = serialized
        .get_mut("cred")
        .and_then(Value::as_object_mut)
        .expect("passkey fixture credential fields");
    credential.insert("backup_eligible".to_owned(), Value::Bool(true));
    credential.insert("backup_state".to_owned(), Value::Bool(true));
    Credential::deserialize_for_test(&serialized.to_string())
        .expect("passkey fixture with backup state decodes")
}

fn fixture_passkey_created_at() -> UtcInstant {
    "2026-09-12T13:14:15.123456Z"
        .parse()
        .expect("valid Passkey fixture created time")
}

fn fixture_passkey_last_used_at() -> UtcInstant {
    "2026-09-12T13:15:16.234567Z"
        .parse()
        .expect("valid Passkey fixture last-used time")
}

/// Timestamps are fixed at microsecond precision because the interop fixture
/// traverses both backends and `PostgreSQL` quantizes timestamps to microseconds.
async fn set_backup_passkey_timestamps(args: &StorageArgs, credential_id: &PasskeyCredentialId) {
    let created_at = fixture_passkey_created_at();
    let last_used_at = fixture_passkey_last_used_at();
    match &args.db {
        storage::DbConnectOptions::Sqlite(options) => {
            let pool = SqlitePoolOptions::new()
                .connect_with(options.clone())
                .await
                .expect("connect SQLite for Passkey fixture timestamps");
            sqlx::query(
                "UPDATE passkey_credentials SET created_at = $1, last_used_at = $2 \
                 WHERE credential_id = $3",
            )
            .bind(created_at)
            .bind(last_used_at)
            .bind(credential_id)
            .execute(&pool)
            .await
            .expect("set SQLite Passkey fixture timestamps");
        }
        storage::DbConnectOptions::Postgres { options, .. } => {
            let pool = PgPoolOptions::new()
                .connect_with(options.clone())
                .await
                .expect("connect PostgreSQL for Passkey fixture timestamps");
            sqlx::query(
                "UPDATE passkey_credentials SET created_at = $1, last_used_at = $2 \
                 WHERE credential_id = $3",
            )
            .bind(created_at)
            .bind(last_used_at)
            .bind(credential_id)
            .execute(&pool)
            .await
            .expect("set PostgreSQL Passkey fixture timestamps");
        }
    }
}

/// Immutable pre-Jiff NDJSON spelling captured from the deployed Chrono backup
/// format. It deliberately differs from Jiff's public `Z` rendering.
const PRE_JIFF_BACKUP_PUBLISHED_AT_BYTES: &[u8] = b"2026-04-29T12:34:56.789012+00:00";

pub fn assert_exported_backup_timestamp_bytes(backup_path: &std::path::Path) {
    let rows = std::fs::read(backup_path.join("db").join("posts.ndjson"))
        .expect("read exported post rows");
    assert!(
        rows.windows(PRE_JIFF_BACKUP_PUBLISHED_AT_BYTES.len())
            .any(|bytes| bytes == PRE_JIFF_BACKUP_PUBLISHED_AT_BYTES),
        "export must retain the established timestamp bytes; rows: {}",
        String::from_utf8_lossy(&rows)
    );
}

/// Rewrites the exported post field from an independently stored pre-Jiff
/// literal before restore. The complete current-schema archive supplies its
/// generated schema checksum and table set, while this input is deliberately
/// not sourced from the current exporter.
pub fn make_pre_jiff_backup_fixture(backup_path: &std::path::Path) {
    let rows_path = backup_path.join("db").join("posts.ndjson");
    let rows = std::fs::read_to_string(&rows_path).expect("read exported post rows");
    let mut rewritten = 0;
    let rows = rows
        .lines()
        .map(|line| {
            let mut row: serde_json::Value = serde_json::from_str(line).expect("parse post row");
            if row["published_at"].is_string() {
                row["published_at"] = serde_json::json!(
                    std::str::from_utf8(PRE_JIFF_BACKUP_PUBLISHED_AT_BYTES)
                        .expect("pre-Jiff timestamp is UTF-8")
                );
                rewritten += 1;
            }
            serde_json::to_string(&row).expect("serialize pre-Jiff post row")
        })
        .collect::<Vec<_>>()
        .join("\n");
    assert!(
        rewritten >= 2,
        "fixture must contain both public and Named post timestamps"
    );
    std::fs::write(rows_path, format!("{rows}\n")).expect("write pre-Jiff post rows");
    assert_exported_backup_timestamp_bytes(backup_path);

    let manifest_path = backup_path.join("manifest.json");
    let mut manifest: serde_json::Value =
        serde_json::from_slice(&std::fs::read(&manifest_path).expect("read manifest"))
            .expect("parse manifest");
    manifest
        .as_object_mut()
        .expect("manifest object")
        .remove("format_version");
    std::fs::write(
        manifest_path,
        serde_json::to_vec_pretty(&manifest).expect("serialize pre-Jiff manifest"),
    )
    .expect("write pre-Jiff manifest");
}

/// Replaces the Named-audience post timestamp in a backup table row with a
/// value beyond Jiff's supported range. The public post remains first and
/// readable, making the decoder boundary observable row-by-row.
pub fn replace_named_post_timestamp_with_out_of_range(
    backup_path: &std::path::Path,
    public_post: PostId,
    named_post: PostId,
) {
    let rows_path = backup_path.join("db").join("posts.ndjson");
    let rows = std::fs::read_to_string(&rows_path).expect("read exported post rows");
    let public_post = serde_json::to_value(public_post).expect("serialize public post id");
    let named_post = serde_json::to_value(named_post).expect("serialize named post id");
    let mut public_index = None;
    let mut named_index = None;
    let rows = rows
        .lines()
        .enumerate()
        .map(|(index, line)| {
            let mut row: serde_json::Value = serde_json::from_str(line).expect("parse post row");
            if row["post_id"] == public_post {
                public_index = Some(index);
            }
            if row["post_id"] == named_post {
                row["published_at"] = serde_json::json!("10000-01-01T00:00:00+00:00");
                named_index = Some(index);
            }
            serde_json::to_string(&row).expect("serialize post row")
        })
        .collect::<Vec<_>>()
        .join("\n");
    assert!(
        public_index < named_index,
        "supported post row must precede the out-of-range post row"
    );
    std::fs::write(rows_path, format!("{rows}\n")).expect("write modified post rows");
}

pub fn assert_fixture_timestamp_meaning(instant: UtcInstant) {
    let rendered = instant.to_string();
    assert_eq!(rendered, "2026-04-29T12:34:56.789012Z");
    assert_eq!(&rendered[..10], "2026-04-29", "civil date");
    assert_eq!(&rendered[20..26], "789012", "microsecond precision");
    assert!(rendered.ends_with('Z'), "UTC timezone meaning");
}

/// Shows a valid backup row remains readable until a later out-of-range row is
/// decoded through the normal storage query path.
pub async fn assert_supported_post_precedes_out_of_range_post(
    args: &StorageArgs,
    ids: &BackupFixtureIds,
) {
    let factory = open_existing_database(&args.db, &StorageRuntimeConfig::default())
        .await
        .expect("open restored database");
    let posts = factory.posts();
    assert!(
        posts
            .get_post_by_id(ids.public_post, &ViewerIdentity::local(ids.author))
            .await
            .expect("decode supported preceding post row")
            .is_some(),
        "supported row preceding the out-of-range row must remain readable"
    );
    posts
        .get_post_by_id(ids.named_post, &ViewerIdentity::local(ids.viewer))
        .await
        .expect_err("decoding the out-of-range post row must fail");
}

pub async fn populate_backup_fixture(args: &StorageArgs) -> BackupFixtureIds {
    let factory = open_existing_database(&args.db, &storage::StorageRuntimeConfig::default())
        .await
        .expect("open database");
    let write_scope = factory.write_scope();
    let publisher_generation =
        configure_backup_publisher(factory.publisher(), write_scope.clone()).await;
    let (author, password) = create_backup_author(factory.users(), write_scope.clone()).await;
    let passkey = seed_backup_passkey(args, factory.passkeys(), write_scope.clone(), author).await;
    let public = SeedRawPost::new(author)
        .published_at(fixture_published_at())
        .tags(["Backup-Test"])
        .seed(factory.posts(), write_scope.clone())
        .await;
    seed_historical_permalink_alias(args, public.post_id, author).await;
    let (viewer, audience, subscription, named_post) = seed_named_audience_post(
        factory.users(),
        factory.subscriptions(),
        factory.audiences(),
        factory.posts(),
        write_scope.clone(),
        author,
        &password,
    )
    .await;
    seed_side_tables(
        factory.user_config(),
        factory.media(),
        factory.feed_events(),
        write_scope,
        author,
    )
    .await;
    std::fs::write(args.storage_path.join("media").join("avatar.txt"), "media")
        .expect("write media");
    BackupFixtureIds {
        author,
        viewer,
        public_post: public.post_id,
        public_post_slug: public.slug,
        public_post_title: public.title,
        named_post,
        audience,
        subscription,
        publisher_generation,
        passkey_user_handle: passkey.user_handle,
        passkey_credential_id: passkey.credential_id,
        passkey_label: passkey.label,
        passkey_serialization: passkey.serialization,
        passkey_created_at: passkey.created_at,
        passkey_last_used_at: passkey.last_used_at,
    }
}

