//! One typed source contract per invocation; no scheduling or policy registration.
#[derive(Clone, Copy, Debug)]
pub enum Operation {
    TestPatternCheck,
    ServerFnRegistrarCheck,
    ServerFnTracingCheck,
    ServerFnWireArgErrorCheck,
    TracedContextCheck,
    E2eTelemetryBoundaryCheck,
    E2eCollectorConfigCheck,
    ProfferedSecretCheck,
    E2eGotoWrapperCheck,
    E2eServerFnEndpointCheck,
    TargetArchPlacementCheck,
    WriteTransactionContractCheck,
    CommonHostTargetClosure,
    LintSuppressionCheck,
    ThinComponents,
    SqlxNewtypeBindCheck,
    RawHtmlDoorCheck,
    HtmlSinkCheck,
    E2eScaffoldCheck,
    XlangLiteralCheck,
    SqlxNewtypeDecode,
    ServerFnCoverage,
}
impl Operation {
    /// Independent verdict identity, not a workflow or result envelope.
    pub fn name(self) -> &'static str {
        match self {
            Self::ServerFnRegistrarCheck => "server-fn-registrar",
            Self::ServerFnTracingCheck => "server-fn-tracing",
            Self::ServerFnWireArgErrorCheck => "server-fn-wire-arg-error",
            Self::TracedContextCheck => "traced-context",
            Self::E2eTelemetryBoundaryCheck => "e2e-telemetry-boundary",
            Self::E2eCollectorConfigCheck => "e2e-collector-config",
            Self::ProfferedSecretCheck => "proffered-secret",
            Self::E2eGotoWrapperCheck => "e2e-goto-wrapper",
            Self::TargetArchPlacementCheck => "target-arch-placement",
            Self::WriteTransactionContractCheck => "write-transaction-contract",
            Self::CommonHostTargetClosure => "common-host-target-closure",
            Self::LintSuppressionCheck => "lint-suppression",
            Self::ThinComponents => "thin-components",
            Self::SqlxNewtypeBindCheck => "sqlx-newtype-bind",
            Self::RawHtmlDoorCheck => "raw-html-door",
            Self::HtmlSinkCheck => "html-sink",
            Self::E2eScaffoldCheck => "e2e-scaffold",
            Self::XlangLiteralCheck => "xlang-literal",
            Self::TestPatternCheck => "test-backend-pattern",
            Self::E2eServerFnEndpointCheck => "e2e-server-fn-endpoints",
            Self::SqlxNewtypeDecode => "sqlx-newtype-decode",
            Self::ServerFnCoverage => "server-fn-coverage",
        }
    }
    pub fn parse(name: &str) -> Option<Self> {
        match name {
            "server-fn-registrar" => Some(Self::ServerFnRegistrarCheck),
            "server-fn-tracing" => Some(Self::ServerFnTracingCheck),
            "server-fn-wire-arg-error" => Some(Self::ServerFnWireArgErrorCheck),
            "traced-context" => Some(Self::TracedContextCheck),
            "e2e-telemetry-boundary" => Some(Self::E2eTelemetryBoundaryCheck),
            "e2e-collector-config" => Some(Self::E2eCollectorConfigCheck),
            "proffered-secret" => Some(Self::ProfferedSecretCheck),
            "e2e-goto-wrapper" => Some(Self::E2eGotoWrapperCheck),
            "target-arch-placement" => Some(Self::TargetArchPlacementCheck),
            "write-transaction-contract" => Some(Self::WriteTransactionContractCheck),
            "common-host-target-closure" => Some(Self::CommonHostTargetClosure),
            "lint-suppression" => Some(Self::LintSuppressionCheck),
            "thin-components" => Some(Self::ThinComponents),
            "sqlx-newtype-bind" => Some(Self::SqlxNewtypeBindCheck),
            "raw-html-door" => Some(Self::RawHtmlDoorCheck),
            "html-sink" => Some(Self::HtmlSinkCheck),
            "e2e-scaffold" => Some(Self::E2eScaffoldCheck),
            "xlang-literal" => Some(Self::XlangLiteralCheck),
            "test-patterns" => Some(Self::TestPatternCheck),
            "e2e-server-fn-endpoints" => Some(Self::E2eServerFnEndpointCheck),
            "sqlx-newtype-decode" => Some(Self::SqlxNewtypeDecode),
            "server-fn-coverage" => Some(Self::ServerFnCoverage),
            _ => None,
        }
    }
    pub fn check(self) -> Result<Option<String>, String> {
        match self {
            Self::TestPatternCheck => super::test_pattern_check::run(),
            Self::ServerFnRegistrarCheck => super::server_fn_registrar_check::run(),
            Self::ServerFnTracingCheck => super::server_fn_tracing_check::run(),
            Self::ServerFnWireArgErrorCheck => super::server_fn_wire_arg_error_check::run(),
            Self::TracedContextCheck => super::traced_context_check::run(),
            Self::E2eTelemetryBoundaryCheck => super::e2e_telemetry_boundary_check::run(),
            Self::E2eCollectorConfigCheck => super::e2e_collector_config_check::run(),
            Self::ProfferedSecretCheck => super::proffered_secret_check::run(),
            Self::E2eGotoWrapperCheck => super::e2e_goto_wrapper_check::run(),
            Self::E2eServerFnEndpointCheck => super::e2e_server_fn_endpoint_check::run(),
            Self::TargetArchPlacementCheck => super::target_arch_placement_check::run(),
            Self::WriteTransactionContractCheck => super::write_transaction_contract_check::run(),
            Self::CommonHostTargetClosure => super::common_host_target_closure::run(),
            Self::LintSuppressionCheck => super::lint_suppression_check::run(),
            Self::ThinComponents => super::thin_components::run(),
            Self::SqlxNewtypeBindCheck => super::sqlx_newtype_bind_check::run(),
            Self::RawHtmlDoorCheck => super::raw_html_door_check::run(),
            Self::HtmlSinkCheck => super::html_sink_check::run(),
            Self::E2eScaffoldCheck => super::e2e_scaffold_check::run(),
            Self::XlangLiteralCheck => super::xlang_literal_check::run(),
            Self::SqlxNewtypeDecode => super::sqlx_newtype_decode_check::run(),
            Self::ServerFnCoverage => crate::source_inventory::run(),
        }
    }
}
